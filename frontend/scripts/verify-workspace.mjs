import assert from 'node:assert/strict'
import { createHash, randomUUID } from 'node:crypto'
import { chromium } from 'playwright-core'

const base = process.env.OEM_BROWSER_URL ?? 'http://127.0.0.1:5173'
const executablePath = process.env.OEM_CHROMIUM ?? '/usr/bin/chromium'
const agentId = process.env.OEM_BROWSER_AGENT ?? 'oem-test-agent-01'
const cppAgent = process.env.OEM_BROWSER_CPP_AGENT
const secondAgent = process.env.OEM_BROWSER_SECOND_AGENT ?? agentId
const browser = await chromium.launch({ executablePath })

try {
  const page = await browser.newPage({ baseURL: base, viewport: { width: 1440, height: 1000 } })
  await page.goto(base)
  const button = name => page.getByRole('button', { name, exact: true })
  const input = name => page.getByLabel(name, { exact: true })
  const status = text => page.getByRole('status').filter({ hasText: text }).waitFor({ timeout: 60_000 })
  const processor = name => input(`Configure ${name}`)
  const deploy = async (action = 'Deploy flow') => {
    const created = page.waitForResponse(response => response.url().endsWith('/api/v1/deployments')
      && response.request().method() === 'POST')
    await button(action).click()
    const response = await created
    assert.equal(response.status(), 200)
    const item = await response.json()
    await page.waitForFunction(async id => {
      const state = await fetch(`/api/v1/deployments/${id}`).then(result => result.json())
      if (state.status === 'FAILED') throw new Error(`Agent rejected deployment ${id}`)
      return state.status === 'APPLIED'
    }, item.id, { timeout: 60_000, polling: 500 })
    await status('Deployment APPLIED (FULLY_APPLIED)')
    return item
  }

  await button('Load test flow').click()
  const flowName = `Browser flow ${randomUUID().slice(0, 8)}`
  await input('Flow name').fill(flowName)
  await processor('GenerateFlowFile').click()
  await button('General').click()
  await input('Processor name').fill('Browser generator')
  await input('Comments').fill('Persisted processor comments')
  await button('Scheduling').click()
  await input('Run schedule').fill('2 sec')
  await button('Properties').click()
  await input('Data Format').selectOption('Text')
  await input('Custom Text').fill('Browser sample A')
  await input('Batch Size').fill('2')
  await input('Attribute name').fill('sample.source')
  await input('Attribute value').fill('browser')
  await button('Add attribute').click()

  await processor('LogAttribute').click()
  await input('Log Prefix').fill('Browser log A')
  await input('Log Payload').check()

  await input('Inspect connection').selectOption('generated-file')
  await input('Connection name').fill('Browser queue')
  await input('Back pressure objects').fill('25')

  await button('Save draft').click()
  await status('Draft saved (v1)')
  const flow = page.getByRole('button', { name: new RegExp(flowName) })
  await flow.click()
  await processor('Browser generator').click()
  assert.equal(await input('Custom Text').inputValue(), 'Browser sample A')
  assert.equal(await input('sample.source').inputValue(), 'browser')
  await button('Scheduling').click()
  assert.equal(await input('Run schedule').inputValue(), '2 sec')
  await input('Inspect connection').selectOption('generated-file')
  assert.equal(await input('Back pressure objects').inputValue(), '25')
  assert.equal(await input('Connection name').inputValue(), 'Browser queue')

  // Inventory membership on its own must not enable deployment.
  const inventoryId = `browser-inventory-${randomUUID().slice(0, 8)}`
  const inventory = await page.request.post(`/api/v1/agents/${inventoryId}/heartbeat`, {
    data: { runtime: 'minifi-java', runtime_version: '2.12.0' },
  })
  assert.equal(inventory.ok(), true)
  const disabledTarget = input('Target agent').locator(`option[value="${inventoryId}"]`)
  await disabledTarget.waitFor({ state: 'attached' })
  assert.equal(await disabledTarget.evaluate(option => option.disabled), true)
  assert.match(await disabledTarget.textContent(), /deployments disabled/)
  await input('Target agent').selectOption(agentId)
  const first = await deploy('Publish and deploy')
  assert.equal(first.version, 1)

  await processor('Browser generator').click()
  await input('Custom Text').fill('{"source":"Browser sample B"}')
  await input('Inspect connection').selectOption('generated-file')
  await button('Remove connection').click()
  await input('Controller service type').selectOption('JsonTreeReader')
  await button('Add service').click()
  await input('Service name').fill('Browser JSON reader')
  await input('Controller service type').selectOption('JsonRecordSetWriter')
  await button('Add service').click()
  await input('Service name').fill('Browser JSON writer')
  await input('Pretty Print JSON').check()
  await input('Processor palette').fill('ConvertRecord')
  await button('ConvertRecord').click()
  await input('Record Reader').selectOption({ label: 'Browser JSON reader' })
  await input('Record Writer').selectOption({ label: 'Browser JSON writer' })
  await input('Connection source').selectOption({ label: 'Browser generator' })
  await input('Connection destination').selectOption({ label: 'ConvertRecord' })
  await button('Add connection').click()
  await input('Connection source').selectOption({ label: 'ConvertRecord' })
  await input('Connection destination').selectOption({ label: 'LogAttribute' })
  await button('Add connection').click()
  await button('Save draft').click()
  await status('Draft saved (v2)')
  await button('Publish flow').click()
  await status('Published v2')
  await input('Target agent').selectOption(secondAgent)
  const second = await deploy()
  assert.equal(first.agent_id, agentId)
  assert.equal(second.agent_id, secondAgent)
  const saved = await page.request.get(`/api/v1/flows/${second.flow_id}`)
  const { definition } = await saved.json()
  const reader = definition.controller_services.find(item => item.type === 'JsonTreeReader')
  const writer = definition.controller_services.find(item => item.type === 'JsonRecordSetWriter')
  const convert = definition.nodes.find(item => item.type === 'ConvertRecord')
  assert.equal(writer.config['Pretty Print JSON'], true)
  assert.equal(convert.config['Record Reader'], reader.id)
  assert.equal(convert.config['Record Writer'], writer.id)
  assert.equal(definition.connections.length, 2)
  assert.ok(definition.connections.some(edge => edge.source === convert.id && edge.source_relationship === 'success'))
  assert.notEqual(first.sha256, second.sha256)
  assert.equal(first.flow_id, second.flow_id)

  await button('v1 Published').click()
  await processor('Browser generator').click()
  assert.equal(await input('Custom Text').inputValue(), 'Browser sample A')
  assert.equal(await input('Custom Text').isDisabled(), true)

  await button('Edge Agents').click()
  await input('Agent ID or hostname').fill(agentId)
  await button('View deployments').click()
  await input('Status').selectOption('APPLIED')
  await page.getByRole('row').filter({ hasText: flowName }).filter({ hasText: 'Version 1' }).waitFor()
  await input('Agent ID').fill(secondAgent)
  await page.getByRole('row').filter({ hasText: flowName }).filter({ hasText: 'Version 2' }).waitFor()
  if (cppAgent) {
    await button('Flow Manager').click()
    await button('New flow').click()
    await input('Flow runtime').selectOption('minifi-cpp')
    await button('UpdateAttribute').waitFor()
    await button('ConvertRecord').waitFor()
    await button('ExecuteScript').waitFor()
    await button('FetchSmb').waitFor()
    await button('ExecuteScript').click()
    await processor('ExecuteScript').click()
    assert.equal(await input('Script Engine').inputValue(), 'python')
    await input('Script Body').fill('def onTrigger(context, session):\n    pass')
    const javaTarget = input('Target agent').locator(`option[value="${agentId}"]`)
    assert.equal(await javaTarget.evaluate(option => option.disabled), true)
    assert.match(await javaTarget.textContent(), /different runtime/)
    page.once('dialog', dialog => dialog.accept())
    await button('Load test flow').click()
    await input('Flow name').fill(`Browser native ${randomUUID().slice(0, 8)}`)
    await processor('GenerateFlowFile').click()
    await input('Data Format').selectOption('Text')
    await input('Unique FlowFiles').uncheck()
    await input('Custom Text').fill('Browser native first')
    await processor('LogAttribute').click()
    await input('Log Payload').check()
    await input('Maximum Payload Line Length').fill('36')
    await button('Save draft').click()
    await status('Draft saved (v1)')
    await input('Target agent').selectOption(cppAgent)
    const nativeFirst = await deploy('Publish and deploy')
    assert.equal(nativeFirst.runtime, 'minifi-cpp')

    await processor('GenerateFlowFile').click()
    await input('Custom Text').fill('Browser native second')
    await button('Save draft').click()
    await status('Draft saved (v2)')
    const nativeSecond = await deploy('Publish and deploy')
    assert.equal(nativeSecond.agent_id, cppAgent)
    assert.notEqual(nativeSecond.sha256, nativeFirst.sha256)
    const record = await page.request.get(`/api/v1/flows/${nativeSecond.flow_id}`)
    const native = (await record.json()).definition
    assert.equal(native.runtime, 'minifi-cpp')
    assert.equal(native.nodes[0].config['Custom Text'], 'Browser native second')
    assert.equal(native.nodes[1].config['Maximum Payload Line Length'], 36)
    await button('v1 Published').click()
    assert.equal(await input('Flow runtime').inputValue(), 'minifi-cpp')
    await processor('GenerateFlowFile').click()
    assert.equal(await input('Custom Text').inputValue(), 'Browser native first')
    console.log(`Browser passed: persisted and deployed both native revisions to ${cppAgent}.`)
  }
  const nifiPort = process.env.OEM_BROWSER_NIFI_PORT
  if (nifiPort) {
    await button('Flow Manager').click()
    for (const [runtime, agent] of [['minifi-java', agentId], ['minifi-cpp', cppAgent]]) {
      if (!agent) continue
      await button('New flow').click()
      await input('Flow runtime').selectOption(runtime)
      await input('Processor palette').fill('GenerateFlowFile')
      await button('GenerateFlowFile').click()
      const data = `Browser Site-to-Site ${runtime} ${randomUUID()}`
      await input('Flow name').fill(`Browser Site-to-Site ${runtime}`)
      await input('Data Format').selectOption('Text')
      await input('Unique FlowFiles').uncheck()
      await input('Custom Text').fill(data)
      await input('Processor palette').fill('Remote Process Group')
      await button('Remote Process Group').click()
      const catalog = input('NiFi Input Port')
      await catalog.selectOption(nifiPort)
      assert.match(await catalog.locator('option:checked').textContent(), new RegExp(nifiPort))
      await input('Connection source').selectOption({ label: 'GenerateFlowFile' })
      await input('Connection destination').selectOption({ label: 'Remote Process Group' })
      await button('Add connection').click()
      await button('Save draft').click()
      await status('Draft saved (v1)')
      await input('Target agent').selectOption(agent)
      const queued = await deploy('Publish and deploy')
      const record = await page.request.get(`/api/v1/flows/${queued.flow_id}`)
      const graph = (await record.json()).definition
      assert.equal(graph.nodes.find(item => item.type === 'RemoteProcessGroup').target_port_id, nifiPort)
      assert.equal(graph.nodes.find(item => item.type === 'GenerateFlowFile').config['Custom Text'], data)
      await button('v1 Published').click()
      await processor('Remote Process Group').click()
      assert.equal(await input('NiFi Input Port').inputValue(), nifiPort)
      console.log(`Browser Site-to-Site payload ${createHash('sha256').update(data).digest('hex')}`)
    }
  }
  console.log(`Browser passed: showed an ineligible inventory agent, published and deployed v1, persisted controller services, and applied v2 (targets: ${agentId}, ${secondAgent}).`)
} finally {
  await browser.close()
}
